// # Student Manager - Full Stack CRUD Project

// ## Project Overview

// Student Manager is a basic full-stack CRUD application built using React for the frontend, Express.js and Node.js for the backend, and MySQL for the database.

// The application allows users to:

// - Add students
// - View students
// - Edit students
// - Update student details
// - Delete students

// ## Technologies Used

// - React
// - JavaScript
// - Node.js
// - Express.js
// - CORS
// - MySQL
// - SQL
// - Fetch API

